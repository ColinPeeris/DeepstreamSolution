"""Run the Triton-vs-nvinfer multi-stream benchmark.

Designed to run *inside* the DeepStream container (repository mounted at
``/workspace``). For each generated config in ``benchmarks/configs/`` it:

1. ensures the Triton server is running for ``triton``-backend configs and
   stopped for ``nvinfer``-backend configs (single-system A/B fairness);
2. launches ``pipeline_launcher.py <config>``, measuring whole-pipeline wall
   time from process start to exit (EOS);
3. parses the per-model timing summary from ``Utils/timing.py``;
4. computes end-to-end throughput = ``streams * frames_per_stream / wall_s``.

Repeating each config gives mean/std across runs. Results are written as CSV
under ``benchmarks/results/<family>/`` (one subdir per pipeline family) plus
the full run logs.

Families correspond to the configs generated by ``make_configs.py``:
``lpr`` (full LPR pipeline) or ``detector_tracker`` (TrafficCamNet detector +
tracker only).

Usage (repo root, in container)::

    python3 benchmarks/run_benchmark.py [--streams 16 32] [--backend triton]
                                       [--repeats 3] [--all] [--family lpr]
                                       [--no-manage-triton]

``--streams`` / ``--backend`` filter the config matrix; ``--all`` runs every
config; defaults to the whole matrix with 3 repeats. ``--reparse`` rebuilds
the CSV/summary from existing logs.
"""
import argparse
import csv
import json
import os
import re
import subprocess
import sys
import time
from collections import defaultdict
from typing import Any, Dict, List, Optional, Tuple

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONFIGS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'configs')
RESULTS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'results')

BACKENDS = ('nvinfer', 'triton')
STREAM_SIZES = (1, 16, 32)
FAMILIES = ('lpr', 'detector_tracker')
DEFAULT_FAMILY = FAMILIES[0]

FRAMES_PER_STREAM = 1441  # verified count of sample_720p.h264

TRITON_BIN = '/opt/tritonserver/bin/tritonserver'
TRITON_MODEL_REPO = '/workspace/triton/model_repo'

TIMING_RE = re.compile(
    r'^\s+(?P<name>\S+)\s+'
    r'batch_size=(?P<batch>\d+)\s+'
    r'per_batch=\s*(?P<per_batch>[\d.]+) ms\s+'
    r'per_image=\s*(?P<per_image>[\d.]+) ms\s+'
    r'\(min=\s*[\d.]+\s+max=\s*[\d.]+\s*ms,\s*n=(?P<n>\d+)\)')


def family_results_dir(family: str) -> str:
    return os.path.join(RESULTS_DIR, family)


def config_path(backend: str, streams: int, family: str = DEFAULT_FAMILY) -> str:
    return os.path.join(CONFIGS_DIR, '%s_%s_%d.json' % (family, backend, streams))


def read_streams(config_file: str) -> int:
    with open(config_file) as f:
        cfg = json.load(f)
    vsrc = cfg['video_source']
    if 'filenames' in vsrc:
        return len(vsrc['filenames'])
    return 1


def triton_running() -> bool:
    return subprocess.run(['pgrep', '-x', 'tritonserver'],
                          capture_output=True).returncode == 0


def stop_triton(timeout: int = 120) -> None:
    if not triton_running():
        return
    print('Stopping Triton server ...')
    subprocess.run(['pkill', '-x', 'tritonserver'], check=True)
    deadline = time.time() + timeout
    while triton_running() and time.time() < deadline:
        time.sleep(2)
    if triton_running():
        raise RuntimeError('Triton server did not stop within %ds' % timeout)
    print('Triton server stopped.')


def start_triton(timeout: int = 180, results_dir: str = RESULTS_DIR) -> None:
    if triton_running():
        print('Triton server already running.')
        return
    os.makedirs(results_dir, exist_ok=True)
    triton_log = os.path.join(results_dir, 'triton_server.log')
    print('Starting Triton server (repo=%s) ...' % TRITON_MODEL_REPO)
    log = open(triton_log, 'w')
    subprocess.Popen(
        [TRITON_BIN, '--model-repository', TRITON_MODEL_REPO,
         '--grpc-port', '8001', '--http-port', '8000'],
        stdout=log, stderr=subprocess.STDOUT,
        start_new_session=True)
    deadline = time.time() + timeout
    ready = False
    while time.time() < deadline:
        if triton_running():
            try:
                with open(triton_log) as f:
                    content = f.read()
                if 'Started GRPCInferenceService' in content:
                    ready = True
                    break
            except OSError:
                pass
        time.sleep(2)
    if not ready:
        raise RuntimeError('Triton server did not become ready within %ds' % timeout)
    print('Triton server ready.')


def run_config(config_file: str, repeat_dir: str) -> Tuple[float, float, Optional[Dict[str, Any]], float]:
    """Run one config, returning (wall_s, fps, per_model, num_batches).

    ``per_model`` maps model name -> dict(per_batch, per_image, batch, n).
    Raises RuntimeError if the pipeline exits non-zero.
    """
    log_path = os.path.join(repeat_dir, os.path.basename(config_file) + '.log')
    t0 = time.monotonic()
    with open(log_path, 'w') as log:
        ret = subprocess.run(
            [sys.executable, 'pipeline_launcher.py', config_file],
            cwd=REPO_ROOT,
            stdout=log, stderr=subprocess.STDOUT,
            timeout=1800)
    wall_s = time.monotonic() - t0
    if ret.returncode != 0:
        raise RuntimeError('%s exited rc=%d (see %s)' % (config_file, ret.returncode, log_path))

    # pipeline_launcher.py returns 0 even when GStreamer posts a bus ERROR
    # (bus_call just quits the loop; run() returns None). Guard against such
    # silent startup failures so dead runs never slip into the results.
    with open(log_path) as f:
        content = f.read()
    if 'End-of-stream' not in content:
        raise RuntimeError('%s never reached End-of-stream; pipeline failed '
                           'at startup (see %s)' % (config_file, log_path))

    per_model: Dict[str, Any] = {}
    with open(log_path) as f:
        for line in f:
            m = TIMING_RE.match(line)
            if m:
                per_model[m.group('name')] = {
                    'batch': int(m.group('batch')),
                    'per_batch': float(m.group('per_batch')),
                    'per_image': float(m.group('per_image')),
                    'n': int(m.group('n')),
                }
    streams = read_streams(config_file)
    total_frames = streams * FRAMES_PER_STREAM
    fps = total_frames / wall_s
    return wall_s, fps, per_model, total_frames


def aggregate_rows(rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Collapse repeated runs per config into mean/std rows."""
    by_key: Dict[Tuple[str, int], List[Dict[str, Any]]] = defaultdict(list)
    for row in rows:
        by_key[(row['backend'], row['streams'])].append(row)

    out: List[Dict[str, Any]] = []
    for (backend, streams) in BACKEND_ORDER():
        key = (backend, streams)
        if key not in by_key:
            continue
        group = by_key[key]

        def mean(field: str) -> float:
            vals = [r[field] for r in group if r[field] is not None]
            return sum(vals) / len(vals) if vals else float('nan')

        def stdev(field: str) -> float:
            vals = [r[field] for r in group if r[field] is not None]
            if len(vals) < 2:
                return 0.0
            m = sum(vals) / len(vals)
            return (sum((v - m) ** 2 for v in vals) / (len(vals) - 1)) ** 0.5

        row: Dict[str, Any] = {
            'backend': backend,
            'streams': streams,
            'repeats': len(group),
            'wall_s_mean': mean('wall_s'),
            'wall_s_std': stdev('wall_s'),
            'fps_mean': mean('fps'),
            'fps_std': stdev('fps'),
            'total_frames': group[0]['total_frames'],
        }
        # per-model per_image means (model names from the per_image_* keys)
        model_names = sorted(k[len('per_image_'):] for k in group[0]
                             if k.startswith('per_image_'))
        for name in model_names:
            row['per_image_%s' % name] = mean('per_image_%s' % name)
        out.append(row)
    return out


def BACKEND_ORDER() -> List[Tuple[str, int]]:
    order = []
    for backend in BACKENDS:
        for streams in STREAM_SIZES:
            order.append((backend, streams))
    return order


def format_table(rows: List[Dict[str, Any]]) -> str:
    lines = ['%-8s %5s %10s %9s %4s' %
             ('backend', 'strms', 'wall_s', 'fps', 'rep')]
    for row in rows:
        lines.append('%-8s %5d %10.1f %9.1f %4d' % (
            row['backend'], row['streams'], row['wall_s_mean'],
            row['fps_mean'], row['repeats']))
    return '\n'.join(lines)


def reparse_logs(family: str = DEFAULT_FAMILY) -> int:
    """Rebuild results.csv + summary.txt from existing per-rep run logs.

    Reparses the per-model timing tables from every ``*_rep*`` directory under
    ``RESULTS_DIR/<family>`` and merges them with the wall-time/FPS rows already
    stored in results.csv (those cannot be recovered from the logs).

    Returns:
        0 on success, 1 if results.csv is missing or nothing was parsed.
    """
    results_dir = family_results_dir(family)
    csv_path = os.path.join(results_dir, 'results.csv')
    if not os.path.isfile(csv_path):
        print('ERROR: %s not found; run the benchmark first' % csv_path)
        return 1

    with open(csv_path) as f:
        rows = list(csv.DictReader(f))

    if not rows:
        print('ERROR: results.csv is empty')
        return 1

    parsed_any = False
    for row in rows:
        streams = row['streams']
        backend = row['backend']
        rep = row['repeat']
        log_dir = os.path.join(results_dir, '%s_%s_rep%s' % (backend, streams, rep))
        log_path = os.path.join(log_dir, '%s_%s_%s.json.log' % (family, backend, streams))
        if not os.path.isfile(log_path):
            print('WARN: missing %s' % log_path)
            continue
        per_model: Dict[str, Any] = {}
        with open(log_path) as f:
            for line in f:
                m = TIMING_RE.match(line)
                if m:
                    per_model[m.group('name')] = {
                        'batch': int(m.group('batch')),
                        'per_batch': float(m.group('per_batch')),
                        'per_image': float(m.group('per_image')),
                        'n': int(m.group('n')),
                    }
        for name, st in per_model.items():
            row['per_image_%s' % name] = st['per_image']
        if per_model:
            parsed_any = True
        row['wall_s'] = float(row['wall_s'])
        row['fps'] = float(row['fps'])
        row['total_frames'] = int(row['total_frames'])
        row['streams'] = int(row['streams'])
        row['repeat'] = int(row['repeat'])

    if not parsed_any:
        print('WARN: no per-model timing lines parsed from any log')
        return 1

    fieldnames = list(rows[0].keys())
    with open(csv_path, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    aggregated = aggregate_rows([{**r, 'per_model': {}} for r in rows])
    summary_path = os.path.join(results_dir, 'summary.txt')
    with open(summary_path, 'w') as f:
        f.write(format_table(aggregated) + '\n')
        for row in aggregated:
            for name in [k for k in row if k.startswith('per_image_')]:
                f.write('%s/%d %s: %.2f ms\n'
                        % (row['backend'], row['streams'],
                           name[len('per_image_'):], row[name]))
    print('Re-parsed %d run(s); wrote %s' % (len(rows), csv_path))
    print('Summary: %s' % summary_path)
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--streams', nargs='+', type=int, default=list(STREAM_SIZES))
    ap.add_argument('--backend', nargs='+', default=list(BACKENDS))
    ap.add_argument('--repeats', type=int, default=3)
    ap.add_argument('--manage-triton', action='store_true', default=True,
                    help='start/stop the Triton server around runs as needed')
    ap.add_argument('--no-manage-triton', dest='manage_triton', action='store_false')
    ap.add_argument('--all', action='store_true',
                    help='run the full matrix (overrides filters)')
    ap.add_argument('--warmup', action='store_true',
                    help='run each config once unmeasured before its measured '
                         'repeats (absorbs one-off cold-start costs)')
    ap.add_argument('--reparse', action='store_true',
                    help='only re-parse existing logs into results.csv/summary.txt')
    ap.add_argument('--family', choices=list(FAMILIES), default=DEFAULT_FAMILY,
                    help='pipeline family to run (configs generated by '
                         'make_configs.py); default: %s' % DEFAULT_FAMILY)
    args = ap.parse_args()
    os.makedirs(RESULTS_DIR, exist_ok=True)
    results_dir = family_results_dir(args.family)
    os.makedirs(results_dir, exist_ok=True)

    if args.reparse:
        return reparse_logs(args.family)

    if args.all:
        streams_list = list(STREAM_SIZES)
        backends = list(BACKENDS)
    else:
        streams_list = args.streams
        backends = args.backend
    for s in streams_list:
        if s not in STREAM_SIZES:
            ap.error('--streams must be one of %s' % (STREAM_SIZES,))

    rows: List[Dict[str, Any]] = []

    for backend in backends:
        for streams in streams_list:
            cfg = config_path(backend, streams, args.family)
            if not os.path.isfile(cfg):
                print('WARN: missing %s, skipping' % cfg)
                continue
            if args.manage_triton:
                if backend == 'triton':
                    start_triton(results_dir=results_dir)
                else:
                    stop_triton()
            print('=== %s | %d streams ===' % (backend, streams))
            if args.warmup:
                warmup_dir = os.path.join(results_dir,
                                          '%s_%d_warmup' % (backend, streams))
                os.makedirs(warmup_dir, exist_ok=True)
                run_config(cfg, warmup_dir)
                print('  warmup done')
            for rep in range(1, args.repeats + 1):
                repeat_dir = os.path.join(results_dir, '%s_%d_rep%d' % (backend, streams, rep))
                os.makedirs(repeat_dir, exist_ok=True)
                wall_s, fps, per_model, total_frames = run_config(cfg, repeat_dir)
                row: Dict[str, Any] = {
                    'backend': backend,
                    'streams': streams,
                    'repeat': rep,
                    'wall_s': wall_s,
                    'fps': fps,
                    'total_frames': total_frames,
                    'per_model': per_model,
                }
                for name, st in per_model.items():
                    row['per_image_%s' % name] = st['per_image']
                rows.append(row)
                print('  rep %d: wall=%.1fs fps=%.1f' % (rep, wall_s, fps))

    if args.manage_triton:
        stop_triton()

    if not rows:
        print('No runs completed.')
        return 1

    aggregated = aggregate_rows(rows)
    print('\n===== Summary =====')
    print(format_table(aggregated))
    for row in aggregated:
        names = [k for k in row if k.startswith('per_image_')]
        for name in names:
            print('  %s/%d stream: %s = %.2f ms'
                  % (row['backend'], row['streams'], name[len('per_image_'):],
                     row[name]))

    csv_path = os.path.join(results_dir, 'results.csv')
    all_keys = sorted({k for r in rows for k in r})  # noqa: C401 - rows have extra keys
    # keep a stable column order
    fieldnames = ['backend', 'streams', 'repeat', 'wall_s', 'fps', 'total_frames']
    fieldnames += sorted(k for k in all_keys if k.startswith('per_image_'))
    with open(csv_path, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for r in rows:
            writer.writerow({k: r.get(k, '') for k in fieldnames})
    summary_path = os.path.join(results_dir, 'summary.txt')
    with open(summary_path, 'w') as f:
        f.write(format_table(aggregated) + '\n')
        for row in aggregated:
            for name in [k for k in row if k.startswith('per_image_')]:
                f.write('%s/%d %s: %.2f ms\n'
                        % (row['backend'], row['streams'],
                           name[len('per_image_'):], row[name]))
    print('\nPer-run CSV: %s' % csv_path)
    print('Summary:     %s' % summary_path)
    return 0


if __name__ == '__main__':
    sys.exit(main())